/** States whose subdivisions are stored with their full official name. */
const SELF_NAMING_STATES = new Set(["AK", "LA"]);

/**
 * How a county is written in full for this state.
 *
 * Louisiana has parishes, Alaska has boroughs and census areas, and everywhere
 * else it is "X County". Getting this right matters beyond cosmetics: it goes
 * into the text query sent to the search provider.
 */
export function countyDisplayName(state: string, county: string): string {
  if (county === "") return "";
  if (SELF_NAMING_STATES.has(state.toUpperCase())) return county;
  return `${county} County`;
}

/** Counties for a state, or an empty array if the state isn't covered yet. */
export function countiesForState(state: string | null | undefined): readonly string[] {
  if (typeof state !== "string") return [];
  return COUNTIES_BY_STATE[state.trim().toUpperCase()] ?? [];
}

/** Is county data bundled for this state? Drives the dropdown's fallback. */
export function hasCountyData(state: string | null | undefined): boolean {
  return countiesForState(state).length > 0;
}

/**
 * Match user input against the bundled list, tolerating a "County"/"Parish"
 * suffix and case differences. Returns the canonical stored name, or null.
 */
export function resolveCounty(
  state: string | null | undefined,
  raw: string | null | undefined,
): string | null {
  if (typeof raw !== "string") return null;
  const needle = raw
    .trim()
    .replace(/\s+(county|parish|borough|census area)$/i, "")
    .toLowerCase();
  if (needle === "") return null;

  return (
    countiesForState(state).find(
      (county) =>
        county.toLowerCase() === needle ||
        county.toLowerCase().replace(/\s+(borough|census area)$/i, "") === needle,
    ) ?? null
  );
}
