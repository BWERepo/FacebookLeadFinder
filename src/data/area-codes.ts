const BY_CODE = new Map(AREA_CODES.map((e) => [e.code, e]));

export function areaCodeInfo(code: string | null | undefined): AreaCodeEntry | null {
  if (typeof code !== "string") return null;
  return BY_CODE.get(code.trim()) ?? null;
}

export function isValidAreaCode(code: string | null | undefined): boolean {
  return (
    typeof code === "string" && /^[2-9][0-9]{2}$/.test(code.trim()) && BY_CODE.has(code.trim())
  );
}

/** Every area code that can appear in a given state. */
export function areaCodesForState(state: string | null | undefined): readonly string[] {
  if (typeof state !== "string") return [];
  const upper = state.trim().toUpperCase();
  return AREA_CODES.filter((e) => e.states.includes(upper)).map((e) => e.code);
}
